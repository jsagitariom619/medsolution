create policy "usuarios lectura propia o admin" on public.usuarios for select to authenticated
using (id = auth.uid() or public.rol_actual() = 'Administrador');
create policy "usuarios administra admin" on public.usuarios for update to authenticated
using (public.rol_actual() = 'Administrador') with check (public.rol_actual() = 'Administrador');

create policy "servicios lectura autenticada" on public.servicios for select to authenticated using (true);
create policy "servicios administra admin" on public.servicios for all to authenticated
using (public.rol_actual() = 'Administrador') with check (public.rol_actual() = 'Administrador');
create policy "personal lectura autenticada" on public.personal_consultorio for select to authenticated using (true);
create policy "personal administra admin" on public.personal_consultorio for all to authenticated
using (public.rol_actual() = 'Administrador') with check (public.rol_actual() = 'Administrador');

create policy "pacientes lectura personal" on public.pacientes for select to authenticated using (public.rol_actual() is not null);
create policy "pacientes alta personal" on public.pacientes for insert to authenticated with check (public.rol_actual() is not null);
create policy "pacientes edicion clinica" on public.pacientes for update to authenticated
using (public.rol_actual() in ('Administrador','Médico'))
with check (public.rol_actual() in ('Administrador','Médico'));
create policy "pacientes elimina admin" on public.pacientes for delete to authenticated
using (public.rol_actual() = 'Administrador');

create policy "historias lectura clinica" on public.historias_clinicas for select to authenticated
using (public.rol_actual() in ('Administrador','Médico'));
create policy "historias alta clinica" on public.historias_clinicas for insert to authenticated
with check (public.rol_actual() in ('Administrador','Médico'));
create policy "historias edicion clinica" on public.historias_clinicas for update to authenticated
using (public.rol_actual() in ('Administrador','Médico'))
with check (public.rol_actual() in ('Administrador','Médico'));

create policy "atenciones lectura por rol" on public.atenciones for select to authenticated
using (
  public.rol_actual() in ('Administrador','Médico')
  or (
    public.rol_actual() = 'Auxiliar'
    and (
      estado in ('Pendiente','Pendiente de consulta')
      or not exists (
        select 1 from public.servicios s
        where s.id = atenciones.servicio_id and s.requiere_consulta_medica
      )
    )
  )
);
create policy "atenciones alta personal" on public.atenciones for insert to authenticated
with check (public.rol_actual() is not null and (registrado_por = auth.uid() or registrado_por is null));
create policy "atenciones edicion por rol" on public.atenciones for update to authenticated
using (
  public.rol_actual() in ('Administrador','Médico')
  or (
    public.rol_actual() = 'Auxiliar'
    and not exists (
      select 1 from public.servicios s
      where s.id = atenciones.servicio_id and s.requiere_consulta_medica
    )
  )
)
with check (
  public.rol_actual() in ('Administrador','Médico')
  or (
    public.rol_actual() = 'Auxiliar'
    and not exists (
      select 1 from public.servicios s
      where s.id = atenciones.servicio_id and s.requiere_consulta_medica
    )
  )
);
create policy "atenciones elimina admin" on public.atenciones for delete to authenticated
using (public.rol_actual() = 'Administrador');

