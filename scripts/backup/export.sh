#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

out_dir="${1:?usage: export.sh OUTPUT_DIRECTORY}"
if [[ -z "${SUPABASE_DB_URL_RO:-}" || -z "${SUPABASE_URL:-}" || -z "${SUPABASE_PUBLIC_KEY:-}" ]]; then
  echo 'Required protected GitHub secrets are not configured.' >&2
  exit 2
fi
if [[ "$SUPABASE_DB_URL_RO" != *"db.lirfjvsqpetdfryywefq.supabase.co"* ]]; then
  echo 'The read-only connection does not target the configured MedSolution project.' >&2
  exit 2
fi
if ! command -v supabase >/dev/null || ! command -v pg_dump >/dev/null || ! command -v psql >/dev/null; then
  echo 'Supabase CLI and PostgreSQL client tools are required.' >&2
  exit 2
fi
pg_major="$(pg_dump --version | sed -E 's/.* ([0-9]+)\..*/\1/')"
[[ "$pg_major" == '17' ]] || { echo 'pg_dump 17 is required.' >&2; exit 2; }
mkdir -p "$out_dir/db" "$out_dir/storage/objects"

# The CLI delegates schema/data export to pg_dump. These files stay on the ephemeral runner.
supabase db dump --db-url "$SUPABASE_DB_URL_RO" --role-only --file "$out_dir/db/roles.sql" --log-level error
supabase db dump --db-url "$SUPABASE_DB_URL_RO" --file "$out_dir/db/schema.sql" --log-level error
supabase db dump --db-url "$SUPABASE_DB_URL_RO" --data-only --use-copy \
  --exclude 'storage.buckets_vectors' --exclude 'storage.vector_indexes' \
  --file "$out_dir/db/data.sql" --log-level error

# The CLI's SQL dump does not contain physical Storage object bytes. Export the bucket
# separately through the public Storage API, respecting the production object's current RLS.
node scripts/backup/export-storage.mjs "$out_dir/storage"

cat > "$out_dir/README.txt" <<'EOF'
MedSolution logical backup; generated by the manual GitHub Actions workflow.
Database files include Supabase CLI role, schema and data dumps.
Storage object bytes are separately exported under storage/objects; storage-manifest.json
contains object keys and metadata. Keep the complete archive encrypted at rest.
This package does not contain Supabase-managed physical Auth/Storage schemas, platform
secrets, encryption root keys, or a Supabase-managed physical snapshot. Review the companion
backup documentation and restore-validation report before treating this as a complete recovery.
EOF

(cd "$out_dir" && find . -type f ! -name SHA256SUMS -print0 | sort -z | xargs -0 sha256sum > SHA256SUMS)
echo 'Database and Storage exports completed; plaintext is confined to the ephemeral runner.'
